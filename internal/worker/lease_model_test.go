package worker

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"testing"
	"time"

	"latere.ai/x/lectio/internal/tasks"
)

var update = flag.Bool("update", false, "rewrite the formal models under formal/")

// seconds is d in whole seconds, rounded up.
func seconds(d time.Duration) int64 { return int64((d + time.Second - 1) / time.Second) }

// leaseConstants is formal/LeaseConstants.tla: the lease of a worker, the
// longest a running worker waits to exchange, the longest one exchange takes,
// and the third of the lease inside which a worker must have exchanged to
// sweep for dead workers, in the whole seconds the TLA+ model counts in. The
// lease rounds down and the waits and the third round up, so the model never
// gives a worker more room than the code does.
func leaseConstants() string {
	w := &Worker{Lease: tasks.DefaultLease}
	return fmt.Sprintf(`\* Code generated by TestLeaseConstants in internal/worker. DO NOT EDIT.
---------------------------- MODULE LeaseConstants ----------------------------
Lease == %d
Renewal == %d
Timeout == %d
Third == %d
=============================================================================
`, w.Lease/time.Second, seconds(w.renewal()), seconds(w.bound()), seconds(w.Lease/3))
}

// TestLeaseConstants holds formal/LeaseConstants.tla to the lease and the
// worker's cadence, so the tla gate checks formal/Lease.tla against the
// values the fleet runs with. Rerun with -update after changing one.
func TestLeaseConstants(t *testing.T) {
	path := filepath.Join("..", "..", "formal", "LeaseConstants.tla")
	want := leaseConstants()
	if *update {
		if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v; rerun with -update", path, err)
	}
	if string(got) != want {
		t.Fatalf("%s differs from the worker's lease; rerun go test ./internal/worker -run TestLeaseConstants -update\n--- want\n%s--- got\n%s", path, want, got)
	}
}
